/**
 * Writes every machinery suite from the one table in suites.ts.
 *
 * node --import tsx evals/machinery/lib/suite-gen.ts [--check]
 *
 * One suite file per entry, one task per scenario, and one committed baseline
 * per suite. `--check` exits nonzero when a committed file differs from what
 * the table produces, which is what the contract test runs.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BASELINE_PIN, MACHINERY_SUITES, type MachinerySuite, machineryTaskId } from "./suites.js";

export const SUITE_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * The scenarios run in place against the checkout they measure, the way
 * `behavioral-machinery.yaml` does: the driver isolates Clio's home itself and
 * writes nothing into the workspace, so a per-task copy would only buy a hash
 * of every file in the repository.
 */
const WORKSPACE = "{kind: local, path: ../..}";

/** The machinery is the measure command; the runner has nothing to start. */
const RUNNER = '{kind: external-command, commands: ["true"]}';

/**
 * Generous enough for the one scenario that admits three real dispatch runs,
 * and still short enough that a hang fails the suite rather than the operator's
 * patience. It bounds nothing the digest measures.
 */
const TIMEOUT_MS = 120_000;

export function baselineFileFor(suite: MachinerySuite): string {
	return `baselines/${suite.name}.json`;
}

export function renderSuite(suite: MachinerySuite): string {
	const lines = [
		"# Generated by evals/machinery/lib/suite-gen.ts from the suite table in",
		"# evals/machinery/lib/suites.ts. Edit the table and regenerate; do not edit by hand.",
		"version: 2",
		"suite:",
		`  id: ${suite.id}`,
		`  title: ${suite.title}`,
		"  visibility: public",
		`  description: ${suite.description}`,
		"matrix:",
		"  dimensions: []",
		"  targets:",
		"    - id: default",
		"  repeats: 1",
		"tasks:",
	];
	for (const [index, scenario] of suite.scenarios.entries()) {
		const first = index === 0;
		lines.push(
			`  - id: ${machineryTaskId(suite, scenario)}`,
			`    tags: [machinery, machinery-only, ${suite.name}]`,
			`    workspace: ${first ? `&workspace ${WORKSPACE}` : "*workspace"}`,
			`    runner: ${first ? `&runner ${RUNNER}` : "*runner"}`,
			"    verify:",
			"      measure:",
			`        - node --import tsx evals/machinery/lib/driver.ts --suite ${suite.name} --scenario ${scenario}`,
			`    metrics: ${first ? "&metrics {collect: [task.solved]}" : "*metrics"}`,
			`    timeoutMs: ${first ? `&timeout ${TIMEOUT_MS}` : "*timeout"}`,
		);
	}
	lines.push("baseline:", `  file: ${baselineFileFor(suite)}`, `  pin: [${BASELINE_PIN.join(", ")}]`);
	return `${lines.join("\n")}\n`;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
	const check = process.argv.includes("--check");
	let stale = 0;
	for (const suite of MACHINERY_SUITES) {
		const path = join(SUITE_DIR, `${suite.name}.yaml`);
		const text = renderSuite(suite);
		if (!check) {
			writeFileSync(path, text);
			continue;
		}
		let current = "";
		try {
			current = readFileSync(path, "utf8");
		} catch {}
		if (current !== text) {
			stale += 1;
			process.stderr.write(`stale: ${path}\n`);
		}
	}
	process.exitCode = stale === 0 ? 0 : 1;
}

/**
 * Writes the edit suites from the one scenario table in corpus.ts.
 *
 * node --import tsx evals/tool-bench/lib/suite-gen.ts [--seed <int>] [--check]
 *
 * The suite format has no run-time parameters, and each task id is the
 * scenario id, which already names its split. So each (split, profile) pair
 * gets its own committed file, and the seed is written into every measure
 * command. --check exits nonzero when a committed file differs from what the
 * table produces.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_SEED, type Profile, type Split, scenarioId, templatesFor } from "./corpus.js";

export const SUITE_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");

export const EDIT_SUITES: ReadonlyArray<{ file: string; split: Split; profile: Profile }> = [
	{ file: "edit.yaml", split: "search", profile: "default" },
	{ file: "edit.holdout.yaml", split: "holdout", profile: "default" },
	{ file: "edit.full.yaml", split: "search", profile: "full" },
	{ file: "edit.full.holdout.yaml", split: "holdout", profile: "full" },
];

/**
 * Top-level paths left out of the per-task workspace copy. The runner step
 * (link-deps.sh) links src and node_modules from the candidate checkout; the
 * rest is never loaded by the tool path. The eval runner copies the workspace
 * once per task and hashes every copied file twice for patch metrics, so a
 * small copy keeps one trial of the suite short.
 */
export const WORKSPACE_EXCLUDES = [
	".claude-plugin",
	".github",
	".superpowers",
	"CHANGELOG.md",
	"apps",
	"assets",
	"benchmarks",
	"docs",
	"examples",
	"library",
	"patches",
	"pnpm-lock.yaml",
	"scripts",
	"src",
	"tests",
];

export function renderEditSuite(split: Split, profile: Profile, seed: number = DEFAULT_SEED): string {
	const suffix = profile === "full" ? "-full" : "";
	const lines = [
		"# Generated by evals/tool-bench/lib/suite-gen.ts from the scenario table in",
		"# evals/tool-bench/lib/corpus.ts. Edit the table and regenerate; do not edit by hand.",
		"version: 2",
		"suite:",
		`  id: tool-bench-edit-${split}${suffix}`,
		`  title: Tool bench, edit tool, ${split} split${profile === "full" ? ", full profile with the 100 MB case" : ""}`,
		"  visibility: public",
		`  description: One task per seeded edit scenario (seed ${seed}, split ${split}), measured through invokeRegisteredTool.`,
		"matrix:",
		"  dimensions: []",
		"  targets:",
		"    - id: default",
		"  repeats: 1",
		"tasks:",
	];
	for (const [index, template] of templatesFor(profile).entries()) {
		const id = scenarioId(split, template.key);
		const timeout = template.key.startsWith("size-100m") ? 600000 : 60000;
		const first = index === 0;
		lines.push(
			`  - id: ${id}`,
			`    tags: [tool-bench, edit, ${split}]`,
			`    workspace: ${first ? `&workspace {kind: temp-copy, path: ../.., excludes: [${WORKSPACE_EXCLUDES.join(", ")}]}` : "*workspace"}`,
			`    runner: ${first ? "&runner {kind: external-command, commands: [sh evals/tool-bench/lib/link-deps.sh]}" : "*runner"}`,
			"    verify:",
			"      measure:",
			`        - node --import tsx evals/tool-bench/lib/driver.ts --scenario ${id} --seed ${seed} --split ${split}`,
			`    metrics: ${first ? "&metrics {collect: [task.solved]}" : "*metrics"}`,
			`    timeoutMs: ${timeout}`,
		);
	}
	return `${lines.join("\n")}\n`;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
	const argv = process.argv.slice(2);
	const check = argv.includes("--check");
	const seedAt = argv.indexOf("--seed");
	const seed = seedAt >= 0 ? Number(argv[seedAt + 1]) : DEFAULT_SEED;
	if (!Number.isSafeInteger(seed)) throw new Error("--seed must be an integer");
	let stale = 0;
	for (const suite of EDIT_SUITES) {
		const path = join(SUITE_DIR, suite.file);
		const text = renderEditSuite(suite.split, suite.profile, seed);
		if (!check) {
			writeFileSync(path, text);
			continue;
		}
		let current = "";
		try {
			current = readFileSync(path, "utf8");
		} catch {}
		if (current !== text) {
			stale += 1;
			process.stderr.write(`stale: ${path}\n`);
		}
	}
	process.exitCode = stale === 0 ? 0 : 1;
}

export type RuntimeRoute = (typeof routes)[keyof typeof routes];
export type Route = RuntimeRoute | SchemaRoute;
type Contract<R extends Route> = R extends RuntimeRoute
	? (typeof SchemaRoutes)[R["name"]]
	: R extends SchemaRoute
		? R
		: never;
export type Input<R extends Route> = SchemaInput<Contract<R>>;
export type Output<R extends Route> = SchemaOutput<Contract<R>>;

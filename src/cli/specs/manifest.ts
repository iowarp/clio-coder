/** How a flag carries its value in `help --json`: a switch, free text, a number, a duration (C11) or one of a set. */
export type ManifestValue = "boolean" | "string" | "number" | "duration" | "path" | readonly string[];

/** A flag row: name, aliases, value, repeatable, `both` when the root side is accepted too (C18), deprecated note. */
